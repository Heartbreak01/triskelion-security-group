document.addEventListener("DOMContentLoaded", function () {
  const dropdown = document.getElementById("lang-dropdown");
  const trigger = document.getElementById("lang-trigger");
  const menu = document.getElementById("lang-menu");

  if (!dropdown || !trigger || !menu) return;

  // Generate opsi dropdown
  LANG_LIST.forEach(function (item) {
    const btn = document.createElement("button");
    btn.type = "button";
    btn.className = "lang-option";
    btn.setAttribute("data-lang", item.code);
    btn.setAttribute("role", "option");
    btn.setAttribute("aria-selected", "false");
    btn.innerHTML =
      '<img class="lang-flag" src="' + flagUrl(item.country) + '" ' +
      'alt="' + item.name + '" width="24" height="16" loading="lazy">' +
      '<span class="lang-name">' + item.name + '</span>' +
      '<span class="lang-code">' + item.code.toUpperCase() + '</span>';
    btn.addEventListener("click", function () {
      applyLanguage(item.code);
      closeMenu();
    });
    menu.appendChild(btn);
  });

  // Toggle buka/tutup
  function openMenu() {
    dropdown.classList.add("open");
    trigger.setAttribute("aria-expanded", "true");
    menu.hidden = false;
  }
  function closeMenu() {
    dropdown.classList.remove("open");
    trigger.setAttribute("aria-expanded", "false");
    menu.hidden = true;
  }

  trigger.addEventListener("click", function (e) {
    e.stopPropagation();
    if (dropdown.classList.contains("open")) {
      closeMenu();
    } else {
      openMenu();
    }
  });

  // Klik di luar → tutup
  document.addEventListener("click", function (e) {
    if (!dropdown.contains(e.target)) closeMenu();
  });

  // ESC → tutup
  document.addEventListener("keydown", function (e) {
    if (e.key === "Escape") closeMenu();
  });

  // Tentukan bahasa awal
  const saved = getSavedLanguage();
  const browserLang = navigator.language.slice(0, 2);
  let initial = "id";

  if (saved && translations[saved]) {
    initial = saved;
  } else if (translations[browserLang]) {
    initial = browserLang;
  }

  if (initial !== "id") {
    applyLanguage(initial);
  } else {
    // Pastikan label tombol utama terisi
    applyLanguage("id");
  }
});